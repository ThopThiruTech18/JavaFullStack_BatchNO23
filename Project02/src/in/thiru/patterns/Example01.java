package in.thiru.patterns;

public class Example01 {

	public static void main(String[] args) {

		System.out.println("Pattern started");
		for (int i = 1; i <= 5; i++) {

			for (int j = 1; j <= 5; j++) {

				System.out.print("* ");

			}
			System.out.println();

		}

		System.out.println("Pattern ended");

	}

}
