package in.thiru.patterns;

public class Example14 {

	public static void main(String[] args) {
		
		System.out.println("started pattern");

		
		for (int i = 1; i <=5; i++) {
			
			
			for (int j = 1; j <=i; j++) {
				
				System.out.print(j);
				
			}
			
			System.out.println();
			
		}

		
		
		System.out.println("ended the pattern");
	}

}
